-- MySQL parses these clauses but rejects unsupported exclusions later.
SELECT SUM(a) OVER (ORDER BY b ROWS BETWEEN UNBOUNDED PRECEDING AND CURRENT ROW EXCLUDE CURRENT ROW) FROM t;
SELECT SUM(a) OVER (ORDER BY b ROWS 1 PRECEDING EXCLUDE GROUP) FROM t;
SELECT SUM(a) OVER (ORDER BY b RANGE CURRENT ROW EXCLUDE TIES) FROM t;
SELECT SUM(a) OVER (ORDER BY b GROUPS BETWEEN 1 PRECEDING AND 1 FOLLOWING EXCLUDE NO OTHERS) FROM t;
