CREATE PROCEDURE flow()
BEGIN
 DECLARE x INT DEFAULT 0;
 IF x=0 THEN SET x=1; ELSEIF x=2 THEN SET x=3; ELSE SET x=4; END IF;
 CASE x WHEN 1 THEN SET x=2; ELSE SET x=0; END CASE;
 WHILE x<3 DO SET x=x+1; END WHILE;
 REPEAT SET x=x-1; UNTIL x=0 END REPEAT;
 loop_label: LOOP SET x=x+1; IF x<2 THEN ITERATE loop_label; END IF; LEAVE loop_label; END LOOP loop_label;
END;
