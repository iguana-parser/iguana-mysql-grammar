CREATE TABLE p(id INT, category INT) PARTITION BY LIST COLUMNS(category)
(PARTITION p0 VALUES IN (1,2) COMMENT='first', PARTITION p1 VALUES IN (3,4) ENGINE=InnoDB);
CREATE TABLE k(id INT PRIMARY KEY) PARTITION BY LINEAR KEY ALGORITHM=2 (id) PARTITIONS 4;
CREATE TABLE s(id INT, category INT) PARTITION BY RANGE(id)
SUBPARTITION BY HASH(category) SUBPARTITIONS 2
(PARTITION p0 VALUES LESS THAN(100) (SUBPARTITION s0, SUBPARTITION s1),
 PARTITION p1 VALUES LESS THAN MAXVALUE (SUBPARTITION s2, SUBPARTITION s3));
