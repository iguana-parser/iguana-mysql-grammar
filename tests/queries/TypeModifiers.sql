CREATE TABLE modifiers (
  a CHAR(12) ASCII BINARY,
  b VARCHAR(30) CHARACTER SET utf8mb4 BINARY,
  c CHAR(4) BINARY UNICODE,
  d NATIONAL VARCHAR(20),
  e NCHAR(10),
  f LONG VARCHAR,
  g LONG VARBINARY,
  h DOUBLE PRECISION,
  i INT UNSIGNED ZEROFILL,
  j VARCHAR(20) COLUMN_FORMAT DYNAMIC STORAGE MEMORY
);
